  MANDOFORGE_FINANCE_RECONCILIATION_CONTROLLER_URL
  MANDOFORGE_FINANCE_RECONCILIATION_CONTROLLER_TOKEN
  RUN_STAGE2_FINANCE_CONTROLLERS
  RUN_STAGE2_FINANCE_EXPORT
)

required_job_flags=(
  RUN_STAGE2_PRODUCTION_VALIDATIONS
  RUN_STAGE2_SECRET_LIFECYCLE
  RUN_STAGE2_PROVIDER_ROLLOUT
  RUN_STAGE2_REMOTE_SIDECAR_RECOVERY
  RUN_STAGE2_APPROVAL_DELIVERY
  RUN_STAGE2_CODEX_STALE_POLL
  RUN_STAGE2_EVAL_RELEASE_AUTOMATION
  RUN_STAGE2_OBSERVABILITY_REMEDIATION
  RUN_STAGE2_FINANCE_CONTROLLERS
  VERIFY_STAGE2_VALIDATION_COVERAGE
)

if [[ ! -f "$template" ]]; then
  echo "missing Stage 2 controller env template: $template" >&2
  exit 1
fi

if [[ ! -f "$secret_manifest" ]]; then
  echo "missing Stage 2 controller Secret example: $secret_manifest" >&2
  exit 1
fi

if [[ ! -f "$production_job_manifest" ]]; then
  echo "missing Stage 2 production evidence Job example: $production_job_manifest" >&2
  exit 1
fi

if [[ ! -x "$render_secret_script" ]]; then
  echo "missing executable Stage 2 controller Secret render script: $render_secret_script" >&2
  exit 1
fi

for var in "${required_template_vars[@]}"; do
  if ! grep -q "^${var}=" "$template"; then
    echo "Stage 2 controller env template is missing $var" >&2
    exit 1
  fi
  if ! grep -q "^  ${var}:" "$secret_manifest"; then
    echo "Stage 2 controller Secret example is missing $var" >&2
    exit 1
  fi
done

while IFS= read -r var; do
  if [[ -z "$var" || "$var" == *_TIMEOUT_SECONDS ]]; then
    continue
  fi
  if ! grep -q "^${var}=" "$template"; then
    echo "Stage 2 controller env template is missing source-referenced env $var" >&2
    exit 1
  fi
done < <(grep -Eho 'MANDOFORGE_[A-Z0-9_]*(CONTROLLER|KMS)[A-Z0-9_]*' "$api_source" | sort -u)

if grep -E '(_TOKEN|_KEY_ID|MANDOFORGE_STAGE2_TEAM_ID)=.+' "$template" >/dev/null; then
  echo "Stage 2 controller env template must not contain real token, key, or team id values" >&2
  grep -nE '(_TOKEN|_KEY_ID|MANDOFORGE_STAGE2_TEAM_ID)=.+' "$template" >&2
  exit 1
fi

if grep -E '(_TOKEN|_KEY_ID|MANDOFORGE_STAGE2_TEAM_ID): "[^"]+"' "$secret_manifest" >/dev/null; then
  echo "Stage 2 controller Secret example must not contain real token, key, or team id values" >&2
  grep -nE '(_TOKEN|_KEY_ID|MANDOFORGE_STAGE2_TEAM_ID): "[^"]+"' "$secret_manifest" >&2
  exit 1
fi

if grep -q 'MANDOFORGE_STAGE2_TEAM_ID|.*_TOKEN' "$render_secret_script"; then
  echo "Stage 2 controller Secret render must not require MANDOFORGE_STAGE2_TEAM_ID now that evidence gates auto-discover teams" >&2
  exit 1
fi

for flag in "${required_job_flags[@]}"; do
  if ! grep -q "name: ${flag}" "$job_manifest"; then
    echo "Stage 2 evidence Job is missing opt-in flag $flag" >&2
    exit 1
  fi
done

if ! grep -q "name: mandoforge-stage2-controller-env" "$production_job_manifest"; then
  echo "Stage 2 production evidence Job must consume mandoforge-stage2-controller-env" >&2
  exit 1
fi

if grep -q "name: RUN_STAGE2_PRODUCTION_VALIDATIONS" "$production_job_manifest"; then
  echo "Stage 2 production evidence Job should read validation flags from the Secret, not hard-coded env" >&2
  exit 1
fi

ALLOW_STAGE2_CONTROLLER_PLACEHOLDERS=1 "$render_secret_script" "$template" >/tmp/mandoforge-stage2-controller-secret-render.yaml

if ! grep -q "name: mandoforge-stage2-controller-env" /tmp/mandoforge-stage2-controller-secret-render.yaml; then
  echo "Stage 2 controller Secret render script produced the wrong Secret name" >&2
  exit 1
fi

if ! grep -q "MANDOFORGE_TENANT_ROUTING_CONTROLLER_URL" /tmp/mandoforge-stage2-controller-secret-render.yaml; then
  echo "Stage 2 controller Secret render is missing controller env data" >&2
  exit 1
fi

echo "stage2 controller env template ok"
