  MANDOFORGE_REMOTE_COMPUTER_STATE_SYNC_CONTROLLER_REQUIRED
  MANDOFORGE_REMOTE_COMPUTER_STATE_SYNC_CONTROLLER_URL
  MANDOFORGE_REMOTE_COMPUTER_STATE_SYNC_CONTROLLER_TOKEN
  MANDOFORGE_REMOTE_COMPUTER_SIDECAR_REPLACEMENT_ENABLED
  MANDOFORGE_REMOTE_COMPUTER_SIDECAR_VALIDATION_REQUIRED
  MANDOFORGE_REMOTE_COMPUTER_SIDECAR_VALIDATION_URL
  MANDOFORGE_REMOTE_COMPUTER_SIDECAR_VALIDATION_TOKEN
  RUN_STAGE2_REMOTE_SIDECAR_RECOVERY
  MANDOFORGE_APPROVAL_NOTIFICATION_DEPLOYMENT_CONTROLLER_REQUIRED
