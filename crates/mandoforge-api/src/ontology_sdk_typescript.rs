    #[test]
    fn generated_sdk_is_deterministic_strict_and_proposal_only() {
        let catalog = fixture_catalog();
        assert!(!catalog.actions[0].approval_required);
        let first = generate_typescript_sdk(uuid::Uuid::nil(), &catalog).expect("first output");
        let second = generate_typescript_sdk(uuid::Uuid::nil(), &catalog).expect("second output");
        assert_eq!(first, second);
        assert_eq!(
            first,
            include_str!("../../../examples/mandoforge-osdk-typescript/src/generated/fixture.ts")
        );
        assert!(first.contains("unknown"));
        assert!(!first.contains(": any"));
        for forbidden in ["create:", "update:", "delete:", "approve:", "commit:"] {
            assert!(
                !first.contains(forbidden),
                "generated forbidden method: {forbidden}"
            );
        }
        assert!(first.contains("propose:"));
        assert!(first.contains("export const MANDOFORGE_APPLICATION_ID: string = \"00000000-0000-0000-0000-000000000000\";"));
        assert!(!first.contains("applicationId: string"));
        assert!(first.contains("status: \"approval_required\""));
        assert!(first.contains("status: \"proposal_created\""));
        assert!(
            first.find("if (!response.ok)").expect("status check")
                < first.find("response.json()").expect("JSON parse")
        );
    }

    #[test]
    fn generated_sdk_honors_optional_shorthand_action_parameters() {
        let mut catalog = fixture_catalog();
        catalog.actions[0].input_schema = serde_json::json!({
            "required_name": "string",
            "optional_note": {"type": "string", "required": false},
            "priority": {"type": "number", "enum": [1, 2.5], "required": false},
            "integral_priority": {"type": "integer", "enum": [1.0], "required": false},
            "approved": {"type": "boolean", "enum": [true, false], "required": false},
            "mixed_number": {"type": "number", "enum": [1, "invalid", 2.5], "required": false}
        });

        let output = generate_typescript_sdk(uuid::Uuid::nil(), &catalog).expect("SDK output");

        assert!(output.contains("readonly \"required_name\": string;"));
        assert!(output.contains("readonly \"optional_note\"?: string;"));
        assert!(output.contains("readonly \"priority\"?: 1 | 2.5;"));
        assert!(output.contains("readonly \"integral_priority\"?: 1.0;"));
        assert!(output.contains("readonly \"approved\"?: true | false;"));
        assert!(output.contains("readonly \"mixed_number\"?: 1 | 2.5;"));
    }
